def draw_costs(dist_name, params, size, rng=None):
    if rng is None:
        rng = np.random.default_rng()
    if dist_name.lower() == "lognorm":
        shape, loc, scale = params
        return lognorm.rvs(shape, loc=loc, scale=scale, size=size, random_state=rng)
    elif dist_name.lower() == "gamma":
        shape, loc, scale = params
        return gamma.rvs(shape, loc=loc, scale=scale, size=size, random_state=rng)
    else:
        raise ValueError("dist_name must be 'lognorm' or 'gamma'")

# -------------------------------
# Simulation Function
# -------------------------------
def run_simulation(n_iterations, n1, n2, p1, p2, cost_dist_group1, params_group1, cost_dist_group2, params_group2, rng):
    simulated_icer_estimates = []
    eps = 1e-9 # guard for near-zero denominator

    for _ in range(n_iterations):
        # (i) Draw cost data from the chosen fitted distributions
        simulated_costs_group1 = draw_costs(cost_dist_group1, params_group1, n1, rng)
        simulated_costs_group2 = draw_costs(cost_dist_group2, params_group2, n2, rng)

        # (ii) Draw events from binomial with p1, p2
        simulated_events_group1 = rng.binomial(1, p1, size=n1)
        simulated_events_group2 = rng.binomial(1, p2, size=n2)

        # Means / proportions in the simulated dataset
        simulated_m1 = simulated_costs_group1.mean()
        simulated_m2 = simulated_costs_group2.mean()
        simulated_p1 = simulated_events_group1.mean()
        simulated_p2 = simulated_events_group2.mean()

        # (iii) ICER
        dC = simulated_m1 - simulated_m2
        dE = simulated_p1 - simulated_p2
        if abs(dE) > eps:
            simulated_icer_estimates.append(dC / dE)

    return np.array(simulated_icer_estimates, dtype=float)

